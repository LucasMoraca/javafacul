public class primeiroproj {
    /*
     * public: Este é um modificador de acesso. Significa que o método main é acessível de qualquer lugar do programa e também de fora do programa
     * 
     * static: Este é um modificador. Indica que o método main pertence à classe em si, e não a uma instância específica dessa classe (objeto). 
     * Isso significa que você pode chamar o método main diretamente usando o nome da classe, sem precisar criar um objeto dessa classe primeiro.
     * 
     * void: Esta é a palavra-chave que indica o tipo de retorno do método. void significa que o método main não retorna nenhum valor após sua execução.
     * 
     * main: Este é o nome do método
     * 
     * (String []args): Esta é a lista de parâmetros do método main.
     */
    public static void main(String []args){
        //Exibirá a menssagem desejada
        System.out.print("Hello Word");
    }
}